// Writes firmware/host_test/vectors.h: protocol v1 bytes built by this Dart reference, so the box firmware is
// tested against exactly what the app sends. Run from packages/vroo_protocol:
//   dart run tool/gen_c_vectors.dart ../../firmware/host_test/vectors.h
import 'dart:io';

import 'package:vroo_protocol/vroo_protocol.dart';

import '../test/fixtures.dart';
import '../test/hex.dart';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/gen_c_vectors.dart <path/to/vectors.h>');
    exit(64);
  }
  final tag = unhex(tagHex);
  final vectors = {
    'VEC_GROUP_TAG': tag,
    'VEC_ENVELOPE': wrapEnvelope(tag, unhex(sealed)),
    'VEC_BOX_CONFIG_FULL': encodeBoxConfig(BoxConfig(groupTag: tag, channel: 11, wifiPassword: 'abcd-efgh-jkmn-pqrs')),
    'VEC_BOX_CONFIG_TAG_ONLY': encodeBoxConfig(BoxConfig(groupTag: tag)),
    'VEC_BOX_STATUS': encodeBoxStatus(const BoxStatus(
        boxId: 0x00A1B2C3, fwVersion: 1, uptimeS: 3600, setupMode: false, phones: 2,
        rxFromPhones: 100, txToPhones: 90, dropDup: 3, dropTag: 1)),
  };
  final out = StringBuffer()
    ..writeln('// SPDX-License-Identifier: GPL-3.0-or-later')
    ..writeln('// Generated by packages/vroo_protocol/tool/gen_c_vectors.dart. Do not edit.')
    ..writeln('#pragma once')
    ..writeln()
    ..writeln('#include <stdint.h>');
  vectors.forEach((name, bytes) {
    final rows = [
      for (var i = 0; i < bytes.length; i += 12)
        bytes.skip(i).take(12).map((b) => '0x${b.toRadixString(16).padLeft(2, '0')}').join(', '),
    ];
    out
      ..writeln()
      ..writeln('static const uint8_t $name[${bytes.length}] = {')
      ..writeln('    ${rows.join(',\n    ')},')
      ..writeln('};');
  });
  File(args.single).writeAsStringSync(out.toString());
}
